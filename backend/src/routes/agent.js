    'function Install-AgentScript($target, $content) {',
    '  # Replacing the currently-running script is the step that was failing',
    '  # silently: it had no try/catch, so a read-only file or a denied write left',
    '  # the agent on the old version with nothing reported anywhere. Several',
    '  # strategies are tried and the result is VERIFIED by reading the file back,',
    '  # because "no exception" is not proof that the bytes landed.',
    '  $script:UpdateError = ""',
    '  $tmp = "$target.new"',
    '  try {',
    '    if (Test-Path $target) { try { Set-ItemProperty -Path $target -Name IsReadOnly -Value $false -ErrorAction SilentlyContinue } catch {} }',
    '    [System.IO.File]::WriteAllText($tmp, $content, (New-Object System.Text.UTF8Encoding($false)))',
    '  } catch {',
    '    $script:UpdateError = "cannot write $($tmp): $($_.Exception.Message)"',
    '    return $false',
    '  }',
    '  $errs = @()',
    '  foreach ($how in @("move", "copy", "iocopy", "direct")) {',
    '    try {',
    '      if     ($how -eq "move")   { Move-Item -Path $tmp -Destination $target -Force -ErrorAction Stop }',
    '      elseif ($how -eq "copy")   { Copy-Item -Path $tmp -Destination $target -Force -ErrorAction Stop }',
    '      elseif ($how -eq "iocopy") { [System.IO.File]::Copy($tmp, $target, $true) }',
    '      else                       { [System.IO.File]::WriteAllText($target, $content, (New-Object System.Text.UTF8Encoding($false))) }',
    '      $onDisk = ""',
    '      try { $onDisk = [System.IO.File]::ReadAllText($target) } catch {}',
    '      if ($onDisk -and $onDisk.Length -ge ($content.Length - 8)) {',
    '        Remove-Item $tmp -Force -ErrorAction SilentlyContinue',
    '        Write-Log "Agent script replaced via $($how)"',
    '        return $true',
    '      }',
    '      $errs += "$($how): wrote but file is $($onDisk.Length) chars"',
    '    } catch { $errs += "$($how): $($_.Exception.Message)" }',
    '  }',
    '  Remove-Item $tmp -Force -ErrorAction SilentlyContinue',
    '  $script:UpdateError = ($errs -join " | ")',
    '  return $false',
    '}',
