    'function Invoke-Bounded($sb, $seconds, $argv) {',
    '  # Hard wall-clock cap for a single call. Needed because WMI and the',
    '  # Defender cmdlets can hang past any -OperationTimeoutSec, and the',
    '  # scheduled task will not start a second instance while one is stuck, so',
    '  # one wedged query silently ends all monitoring for that host until it is',
    '  # rebooted. A runspace can be abandoned; an inline call cannot.',
    '  #',
    '  # Pass anything the scriptblock needs through $argv. The block runs in a',
    '  # FRESH runspace and does NOT inherit caller variables, so a captured',
    '  # $var arrives as $null - which is how the event collectors were quietly',
    '  # broken for a whole release. Use { param($x) ... } together with $argv.',
    '  $ps = [PowerShell]::Create()',
    '  [void]$ps.AddScript($sb)',
    '  if ($argv) { foreach ($a in @($argv)) { [void]$ps.AddArgument($a) } }',
    '  try {',
    '    $h = $ps.BeginInvoke()',
    '    if ($h.AsyncWaitHandle.WaitOne([TimeSpan]::FromSeconds($seconds))) {',
    '      $out = $null',
    '      try { $out = $ps.EndInvoke($h) }',
    '      catch { Write-BoundedError "$($_.Exception.Message)" }',
    '      # A failing cmdlet usually does NOT make EndInvoke throw - the record',
    '      # lands in the runspace error stream instead. That is exactly how a',
    '      # broken collector stayed invisible for a whole release, so the',
    '      # stream is inspected explicitly rather than trusted to raise.',
    '      try {',
    '        if ($ps.HadErrors) {',
    '          foreach ($er in $ps.Streams.Error) { Write-BoundedError "$($er.Exception.Message)" }',
    '        }',
    '      } catch {}',
    '      try { $ps.Dispose() } catch {}',
    '      return $out',
    '    }',
    '    # Timed out. Stop asynchronously and do NOT dispose: when the worker is',
    '    # blocked inside a native provider, Stop() and Dispose() block with it,',
    '    # reintroducing the very hang this function exists to prevent. The',
    '    # runspace is abandoned and dies with the process on the next tick.',
    '    Write-Log "Bounded call exceeded $seconds s - abandoned"',
    '    try { [void]$ps.BeginStop($null, $null) } catch {}',
    '    return $null',
    '  } catch { return $null }',
    '}',
