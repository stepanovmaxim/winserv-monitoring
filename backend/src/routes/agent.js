    'function Get-RansomwareSignals($canaryOn) {',
    '  # Two cheap, high-signal indicators of an encryption run in progress.',
    '  #  * canary files: decoys we plant and hash every pass. Ransomware walks',
    '    #    directories and encrypts everything, so a changed or missing decoy',
    '  #    means it is happening right now, not after the fact.',
    '  #  * shadow copies: wiping restore points is the standard step taken just',
    '  #    before encryption, and the count is readable without any audit policy.',
    '  # Everything is best-effort: this must never be able to break a run.',
    '  $r = @{ canary_enabled = [bool]$canaryOn; canary_total = 0; canary_tripped = 0; tripped = @(); shadow_copies = $null }',
    '  try {',
    '    $sc = Invoke-Bounded { @(Get-CimInstance Win32_ShadowCopy -OperationTimeoutSec 10 -ErrorAction Stop) } 15',
    '    if ($null -ne $sc) { $r.shadow_copies = @($sc).Count }',

    '  } catch {}',
    '  if (-not $canaryOn) { return $r }',
    '  # Marker is deliberately loud so an admin who finds one knows what it is.',
    '  $marker = "WinServ canary file - do not delete or modify. It exists to detect ransomware."',
    '  $dirs = @("$env:PUBLIC\\Documents", "C:\\winserv-agent")',
    '  foreach ($d in $dirs) {',
    '    try {',
    '      if (-not (Test-Path $d)) { continue }',
    '      $f = Join-Path $d "_WinServ_CANARY_DO_NOT_DELETE.txt"',
    '      if (-not (Test-Path $f)) {',
    '        Set-Content -Path $f -Value $marker -Encoding UTF8 -Force -ErrorAction Stop',
    '        try { (Get-Item $f).Attributes = "Hidden" } catch {}',
    '        $r.canary_total++',
    '        continue',
    '      }',
    '      $r.canary_total++',
    '      $now = ""',
    '      try { $now = (Get-Content -Path $f -Raw -ErrorAction Stop) } catch { $now = "<unreadable>" }',
    '      if ($now.Trim() -ne $marker) {',
    '        $r.canary_tripped++',
    '        $r.tripped += $f',
    '        # Put it back so the next pass can detect a further wave.',
    '        try { Set-Content -Path $f -Value $marker -Encoding UTF8 -Force -ErrorAction SilentlyContinue } catch {}',
    '      }',
    '    } catch {}',
    '  }',
    '  return $r',
    '}',
